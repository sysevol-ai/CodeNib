"""Opt-in, bounded first-party funnel events written to ordinary service logs."""

import os
import re
from collections import deque
from time import monotonic
from typing import Literal, Optional

from fastapi import APIRouter, Request, Response
from pydantic import BaseModel, ConfigDict, Field, ValidationError

from ..log_utils import get_logger

router = APIRouter()
logger = get_logger(__name__)
_recent: deque[float] = deque(maxlen=120)
_MAX_EVENT_BYTES = 512
# `name` or `owner/name`, as a published Wiki names its own public repository.
_WIKI_REPOSITORY = r"^[A-Za-z0-9_.-]{1,100}(/[A-Za-z0-9_.-]{1,100})?$"


class ExperienceEvent(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)
    event: Literal[
        "page_view",
        "example_view",
        "example_source_open",
        "example_github_open",
        "example_wiki_open",
        "example_share",
        "repository_submit",
        "generation_form_view",
        "generation_start",
        "first_chapter_read",
        "agent_setup_open",
        "guard_case_view",
        "install_command_copy",
        "guard_first_run",
    ]
    # "cli" is the guard hook's single opt-in first-run event.
    surface: Literal["landing", "wiki", "cli"]
    visit: str = Field(pattern=r"^[a-f0-9]{32}$", max_length=32)
    # A page view may say how its tab arrived, as one coarse class. The
    # browser classifies the referrer; the referrer itself is never sent.
    arrival: Optional[Literal["wiki_link", "search", "social", "github", "other"]] = (
        None
    )
    # Only a landing page view reached from a published Wiki's "Generated by
    # CodeNib" link names that Wiki's repository.
    wiki: Optional[str] = Field(default=None, pattern=_WIKI_REPOSITORY, max_length=201)

    def is_consistent(self) -> bool:
        if (self.surface == "cli") != (self.event == "guard_first_run"):
            return False
        if self.arrival is not None and self.event != "page_view":
            return False
        if (self.arrival == "wiki_link") != (self.wiki is not None):
            return False
        if self.wiki is not None:
            parts = self.wiki.split("/")
            if self.surface != "landing" or any(
                re.fullmatch(r"\.+", part) for part in parts
            ):
                return False
        return True


@router.post("/api/experience-events", status_code=204)
async def experience_event(request: Request):
    if os.environ.get("CODENIB_EXPERIENCE_EVENTS") != "1":
        return Response(status_code=204)
    payload = bytearray()
    async for chunk in request.stream():
        if len(payload) + len(chunk) > _MAX_EVENT_BYTES:
            return Response(status_code=413)
        payload.extend(chunk)
    try:
        event = ExperienceEvent.model_validate_json(payload)
    except ValidationError:
        # Never echo or log the rejected body, including unknown fields.
        return Response(status_code=422)
    if not event.is_consistent():
        return Response(status_code=422)
    now = monotonic()
    # One event-loop operation: there is no await between admission and append.
    # Retain at most 120 timestamps and admit at most 120 logs/minute/worker.
    if len(_recent) == _recent.maxlen and now - _recent[0] < 60:
        return Response(status_code=429, headers={"Retry-After": "60"})
    _recent.append(now)
    detail = "".join(
        f" {name}={value}"
        for name, value in (("arrival", event.arrival), ("wiki", event.wiki))
        if value is not None
    )
    logger.info(
        "experience_event event=%s surface=%s visit=%s%s",
        event.event,
        event.surface,
        event.visit,
        detail,
    )
    return Response(status_code=204, headers={"Cache-Control": "no-store"})
