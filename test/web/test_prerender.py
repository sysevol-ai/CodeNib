"""Readable page documents escape everything and link only where they should."""

import xml.etree.ElementTree as ET

import pytest

from codenib.web.prerender import (
    can_prerender,
    outline_pages,
    page_body,
    page_description,
    page_document,
    page_route,
    plain_text,
    render_markdown,
    robots,
    sitemap,
    standalone_document,
)

SHELL = (
    "<!doctype html><html><head><meta charset='UTF-8' />\n"
    '<meta\n      name="description"\n      content="Site blurb" />\n'
    "<title>CodeNib Wiki · Source-linked repository docs</title>\n"
    '<meta property="og:title" content="Site" />\n'
    '<meta property="og:image" content="https://codenib.ai/card.png" />\n'
    '<meta name="twitter:card" content="summary_large_image" />\n'
    "<script src='/demo/runtime-config.js'></script></head>"
    '<body><div id="root"></div>'
    "<script type='module' src='/demo/assets/app.js'></script></body></html>"
)


def _href(page_id):
    return {"overview": "/demo/r/", "auth": "/demo/r/page/auth/"}.get(page_id)


def test_routes_put_each_page_at_its_own_path():
    assert page_route("psf__requests", "overview") == "psf__requests/"
    assert page_route("psf__requests", "auth") == "psf__requests/page/auth/"


def test_markdown_is_escaped_and_reduced_to_a_fixed_element_set():
    html = render_markdown(
        "## Flow <script>alert(1)</script>\n\n"
        "A **session** sends [requests](?p=auth#retry) via `Session.send` "
        "[E1](#evidence-E1) [R2].\n"
        "See [docs](https://docs.example/x) and [local](./file.py) and "
        "[js](javascript:alert(1)) ![shot](media/a.png).\n\n"
        "- first\n  continued\n- second\n\n"
        "1. one\n2. two\n\n"
        "| a | b |\n|---|---|\n| x | y |\n\n"
        "> quoted\n\n"
        "<div onclick='x'>raw</div>\n\n"
        "```python\nif a < b:\n    pass\n```\n\n"
        "```mermaid\ngraph TD; A-->B\n```\n",
        _href,
    )

    assert "<script>" not in html and "&lt;script&gt;" in html
    assert '<a href="/demo/r/page/auth/#retry">requests</a>' in html
    assert "<code>Session.send</code>" in html
    assert "E1" not in html and "R2" not in html
    assert '<a href="https://docs.example/x" rel="nofollow noopener">docs</a>' in html
    assert "local" in html and "./file.py" not in html
    assert "javascript:" not in html and "media/a.png" not in html
    assert "<ul><li>first continued</li><li>second</li></ul>" in html
    assert "<ol><li>one</li><li>two</li></ol>" in html
    assert "<p>x · y</p>" in html and "---" not in html
    assert "<blockquote><p>quoted</p></blockquote>" in html
    assert "onclick" not in html and "raw" not in html
    assert "<pre><code>if a &lt; b:\n    pass</code></pre>" in html
    assert "graph TD" not in html


def test_link_labels_keep_their_emphasis():
    assert render_markdown("[**core** `api`](?p=auth)", _href) == (
        '<p><a href="/demo/r/page/auth/"><strong>core</strong> <code>api</code></a></p>'
    )


def test_unknown_page_links_keep_only_their_words():
    assert render_markdown("[gone](?p=missing)", _href) == "<p>gone</p>"
    assert render_markdown("[bad](?p=../x)", _href) == "<p>bad</p>"


def test_description_is_the_page_lead_in_plain_words():
    markdown = (
        "# Auth\n\nThe `Session` attaches **credentials** through "
        "[the adapter](?p=auth) before sending [E1](#evidence-E1). More text."
    )
    assert page_description(markdown, "fallback") == (
        "The Session attaches credentials through the adapter before sending. "
        "More text."
    )
    assert page_description("```\ncode\n```", "Auth in the r Wiki.") == (
        "Auth in the r Wiki."
    )
    long = "word " * 80
    assert len(page_description(long, "x")) <= 200
    assert plain_text("<b>x</b> `y`") == "x y"


def test_page_document_carries_its_own_head_and_readable_body():
    body = page_body(
        repository="psf/requests",
        title="Auth",
        markdown="# Auth\n\nThe session signs requests.",
        pages=[("overview", "Overview"), ("auth", "Auth"), ("lost", "Lost")],
        page_href=_href,
        current="auth",
        source="Generated by CodeNib from psf/requests at abc",
    )
    document = page_document(
        SHELL,
        title="Auth · psf/requests Wiki",
        description='Signs "requests" <safely>.',
        canonical="https://o.github.io/demo/r/page/auth/",
        body=body,
        site_name="psf/requests Wiki",
    )

    assert document.count("<title>") == 1
    assert "<title>Auth · psf/requests Wiki</title>" in document
    assert "Site blurb" not in document and "card.png" not in document
    assert (
        '<meta name="description" content="Signs &quot;requests&quot; '
        '&lt;safely&gt;.">' in document
    )
    assert (
        '<link rel="canonical" href="https://o.github.io/demo/r/page/auth/">'
        in document
    )
    assert '<meta property="og:type" content="article">' in document
    assert '<meta name="twitter:card" content="summary">' in document
    # The app still loads and replaces the readable page when it starts.
    assert "src='/demo/assets/app.js'" in document
    assert '<div id="root">\n<main class="prerendered-wiki">' in document
    assert "<h1>Auth</h1>" in document and "<h2>Auth</h2>" not in document
    assert '<a href="/demo/r/page/auth/" aria-current="page">Auth</a>' in document
    assert "Lost" not in document


def test_shells_without_a_title_or_empty_root_are_left_alone():
    assert can_prerender(SHELL)
    assert not can_prerender("<html><body><div id='app'></div></body></html>")
    with pytest.raises(ValueError):
        page_document(
            "<html></html>", title="t", description="d", canonical=None, body=""
        )


def test_without_a_site_url_there_is_no_canonical_link():
    document = page_document(
        SHELL, title="t", description="d", canonical=None, body="<main></main>"
    )
    assert "canonical" not in document and "og:url" not in document


def test_standalone_document_and_crawl_files():
    document = standalone_document(
        title="t", description="d", canonical="https://x.test/r/", body="<main></main>"
    )
    assert document.startswith("<!doctype html>")
    assert "<script" not in document

    root = ET.fromstring(
        sitemap(["https://x.test/r/", "https://x.test/r/", "https://x.test/a&b/"])
    )
    locs = [
        loc.text
        for loc in root.iter("{http://www.sitemaps.org/schemas/sitemap/0.9}loc")
    ]
    assert locs == ["https://x.test/r/", "https://x.test/a&b/"]
    assert robots("https://x.test/sitemap.xml").decode().splitlines() == [
        "User-agent: *",
        "Allow: /",
        "",
        "Sitemap: https://x.test/sitemap.xml",
    ]


def test_outline_pages_follow_reading_order_once():
    tree = [
        {"id": "overview", "title": "Overview", "children": []},
        {"id": "core", "title": "Core", "children": [{"id": "auth", "title": "Auth"}]},
        {"id": "../x", "title": "Bad"},
        {"id": "core", "title": "Core"},
    ]
    assert outline_pages(tree) == [
        ("overview", "Overview"),
        ("core", "Core"),
        ("auth", "Auth"),
    ]
