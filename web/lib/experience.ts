import {
  classifyArrival,
  installExperienceEvents,
  isWikiRepository,
  recordExperience,
} from "../../landing/assets/explore/experience.js";
import { isStaticRuntime } from "./runtime";

export function startExperienceEvents() {
  if (!isStaticRuntime() && window.__CODENIB_RUNTIME__?.experienceEvents === true) {
    // The hosted Wiki records only the arrival class, never a Wiki name.
    installExperienceEvents(
      "/api/experience-events",
      "wiki",
      classifyArrival("", document.referrer, location.hostname),
    );
  }
}

// Where a published Wiki's "Generated by CodeNib" link points. The repository
// name is the Wiki's own public identity: the landing page reads it once,
// counts it only with explicit opt-in, and removes it from the address bar.
export function generatedByHref(repository: string | undefined): string {
  const url = new URL("https://codenib.ai/");
  const name = (repository || "").trim();
  if (isWikiRepository(name)) {
    url.searchParams.set("ref", "wiki");
    url.searchParams.set("repo", name);
  }
  return url.href;
}

