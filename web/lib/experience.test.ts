import { describe, expect, it } from "vitest";

import {
  classifyArrival,
  withoutArrivalParameters,
} from "../../landing/assets/explore/experience.js";
import { generatedByHref } from "./experience";

describe("arrival classes", () => {
  it("names the published Wiki only from its own attribution link", () => {
    expect(classifyArrival("?ref=wiki&repo=psf%2Frequests", "", "codenib.ai")).toEqual({
      arrival: "wiki_link",
      wiki: "psf/requests",
    });
    expect(classifyArrival("?ref=wiki&repo=tokio", "https://x.github.io/", "codenib.ai")).toEqual({
      arrival: "wiki_link",
      wiki: "tokio",
    });
    for (const repo of ["..", "a/..", "a/b/c", "https://evil.test/", "a b", ""]) {
      expect(classifyArrival(`?ref=wiki&repo=${encodeURIComponent(repo)}`, "", "codenib.ai")).toEqual({});
    }
  });

  it("sends a coarse class, never the referrer", () => {
    expect(classifyArrival("", "https://www.google.com/search?q=secret", "codenib.ai")).toEqual({ arrival: "search" });
    expect(classifyArrival("", "https://duckduckgo.com/", "codenib.ai")).toEqual({ arrival: "search" });
    expect(classifyArrival("", "https://news.ycombinator.com/item?id=1", "codenib.ai")).toEqual({ arrival: "social" });
    expect(classifyArrival("", "https://github.com/sysevol-ai/CodeNib", "codenib.ai")).toEqual({ arrival: "github" });
    expect(classifyArrival("", "https://blog.example.com/post", "codenib.ai")).toEqual({ arrival: "other" });
    expect(classifyArrival("", "https://notgoogle.com.evil.test/", "codenib.ai")).toEqual({ arrival: "other" });
    expect(classifyArrival("", "https://codenib.ai/blogs/", "codenib.ai")).toEqual({});
    expect(classifyArrival("", "", "codenib.ai")).toEqual({});
  });

  it("removes the attribution parameters and keeps everything else", () => {
    expect(withoutArrivalParameters("https://codenib.ai/?ref=wiki&repo=psf%2Frequests#example")).toBe(
      "https://codenib.ai/#example",
    );
    expect(withoutArrivalParameters("https://codenib.ai/?ref=wiki&repo=a&task=auth")).toBe(
      "https://codenib.ai/?task=auth",
    );
    expect(withoutArrivalParameters("https://codenib.ai/?repo=a")).toBe("https://codenib.ai/?repo=a");
  });
});

describe("Generated by CodeNib", () => {
  it("links to codenib.ai with the Wiki's public repository name", () => {
    expect(generatedByHref("psf/requests")).toBe("https://codenib.ai/?ref=wiki&repo=psf%2Frequests");
    expect(generatedByHref("requests")).toBe("https://codenib.ai/?ref=wiki&repo=requests");
  });

  it("falls back to the plain homepage for names it cannot vouch for", () => {
    expect(generatedByHref(undefined)).toBe("https://codenib.ai/");
    expect(generatedByHref("../escape")).toBe("https://codenib.ai/");
    expect(generatedByHref("owner/name/extra")).toBe("https://codenib.ai/");
  });
});
