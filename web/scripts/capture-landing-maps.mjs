// Capture the maps the codenib.ai hero shows, from a running CodeNib API,
// into landing-hero/maps.ts (a module:
// *.json is ignored by git here). Rebuild the landing bundle afterwards:
//
//   node scripts/capture-landing-maps.mjs http://127.0.0.1:8000
//   npx vite build --config vite.landing.config.ts

import { writeFileSync } from "node:fs";

const REPOS = [
  { id: "psf__requests", label: "requests", language: "Python" },
  { id: "gin-gonic__gin", label: "gin", language: "Go" },
  { id: "nushell__nushell", label: "nushell", language: "Rust" },
  { id: "fmtlib__fmt", label: "fmt", language: "C++" },
];

const base = process.argv[2];
if (!base) {
  console.error("usage: capture-landing-maps.mjs <api-base>");
  process.exit(2);
}
const get = async (path) => {
  const response = await fetch(`${base}${path}`);
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  return response.json();
};

// Only the Overview section that lists the traced path is needed: a level-two
// heading followed by numbered `**`symbol`**` stages (see extractJourney).
function tracedPathSection(markdown) {
  const sections = markdown.replace(/\r\n?/g, "\n").split(/\n(?=## )/);
  const stage = /^\d+\.\s+\*\*`[^`]+`\*\*/;
  const section = sections.find((block) => {
    const [heading, ...body] = block.split("\n");
    const lines = body.filter((line) => line.trim());
    return /^## /.test(heading) && lines.length >= 2 && lines.every((line) => stage.test(line.trim()));
  });
  return section ? `# Overview\n\n${section.trim()}\n` : "";
}

const infos = await get("/api/repos");
const out = [];
for (const item of REPOS) {
  const info = infos.find((repo) => repo.id === item.id);
  if (!info) throw new Error(`${item.id} is not served by ${base}`);
  const [map, tree, overview] = await Promise.all([
    get(`/api/repos/${item.id}/wiki-map`),
    get(`/api/repos/${item.id}/wiki?cached_only=true`),
    get(`/api/repos/${item.id}/wiki/overview?materialize_media=false`),
  ]);
  out.push({
    ...item,
    repo: {
      repo: info.repo,
      commit_short: info.commit_short,
      base_commit: info.base_commit,
      source_url: info.source_url ?? null,
      file_count: info.file_count,
    },
    map: { available: map.available, reason: map.reason ?? null, areas: map.areas, links: map.links },
    pages: tree.pages,
    overview: tracedPathSection(overview.markdown || ""),
  });
  console.log(`${item.id}: ${map.areas.length} areas, ${map.links.length} links`);
}
writeFileSync(
  new URL("../landing-hero/maps.ts", import.meta.url),
  "// SPDX-FileCopyrightText: 2025-2026 CodeNib Contributors\n" +
    "// SPDX-License-Identifier: Apache-2.0\n\n" +
    "// Generated by scripts/capture-landing-maps.mjs; do not edit.\n" +
    `export default ${JSON.stringify(out)};\n`,
);
