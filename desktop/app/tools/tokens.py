def block(t: dict) -> str:
    v = {
        # Named design tokens
        "--desk": t["desk"], "--sheet": t["sheet"], "--well": t["well"], "--raised": t["raised"],
        "--hover": t["hover"], "--ink": t["ink"], "--ink-2": t["ink2"], "--muted-ink": t["muted"],
        "--line": t["line"], "--line-soft": t["linesoft"], "--nib": t["nib"], "--nib-soft": t["nibsoft"],
        "--nib-line": t["nibline"], "--danger": t["danger"], "--add-bg": t["addbg"], "--add-fg": t["addfg"],
        "--del-bg": t["delbg"], "--del-fg": t["delfg"], "--frame": t["frame"], "--box": t["box"],
        "--frame-color": t["framecolor"], "--box-color": t["boxcolor"], "--shadow-window": t["shwindow"],
        "--shadow-card": t["shcard"], "--shadow-box": t["shbox"], "--shadow-box-hover": t["shboxhover"],
        "--shadow-box-press": t["shboxpress"], "--lift": t["lift"], "--sink": t["sink"],
        "--code-bg": t["codebg"], "--code-hl": t["codehl"], "--radius": t["radius"],
        # shadcn tokens, read from the named ones
        "--background": t["sheet"], "--foreground": t["ink"], "--card": t["raised"], "--card-foreground": t["ink"],
        "--popover": t["raised"], "--popover-foreground": t["ink"], "--primary": t["primary"],
        "--primary-foreground": t["primaryfg"], "--secondary": t["well"], "--secondary-foreground": t["ink"],
        "--muted": t["well"], "--muted-foreground": t["muted"], "--accent": t["hover"], "--accent-foreground": t["ink"],
        "--destructive": t["danger"], "--border": t["line"], "--input": t["line"], "--ring": t["ink2"],
        "--sidebar": t["well"], "--sidebar-foreground": t["ink2"], "--sidebar-primary": t["ink"],
        "--sidebar-primary-foreground": t["sheet"], "--sidebar-accent": t["hover"],
        "--sidebar-accent-foreground": t["ink"], "--sidebar-border": t["line"], "--sidebar-ring": t["ink2"],
        "--area-1": t["a1"], "--area-2": t["a2"], "--area-3": t["a3"], "--area-4": t["a4"],
        "--area-5": t["a5"], "--area-none": t["anone"],
        "color-scheme": t["scheme"],
    }
    return "\n".join(f"  {k}: {val};" for k, val in v.items())


def theme(prefix: str, light: dict, dark: dict) -> str:
    root = f":root{prefix}"
    return (
        f"{root} {{\n{block(light)}\n}}\n"
        f"@media (prefers-color-scheme: dark) {{\n  {root}:not([data-theme=\"light\"]):not(.light) {{\n"
        + block(dark).replace("\n", "\n  ")
        + "\n  }\n}\n"
        f"{root}[data-theme=\"dark\"]:not(.light),\n{root}.dark {{\n{block(dark)}\n}}\n"
    )


css = (
    "/* Generated by tools/tokens.py. Paper & Ink: warm paper and ink in light,\n"
    "   the site's dark family in dark. Light values sit on bare :root; dark values\n"
    "   follow the system unless the host or the app's own toggle says otherwise. */\n\n"
    + theme("", PAPER_LIGHT, PAPER_DARK)
)
Path(__file__).resolve().parents[1].joinpath("src/themes/tokens.css").write_text(css)
print(len(css.splitlines()), "lines")
