"""Summarize opt-in experience events from service logs on stdin.

Counts are browser-tab visits, not people; ``cli`` counts opted-in guard
installations whose hook reported for the first time. Origins have separate sessions;
disabled telemetry, privacy signals, blocked requests and rate limiting make
these partial observations, not a census or a causal conversion estimate.

A tab's first page view may carry one arrival class (search, social, github,
wiki_link or other; none means direct or unknown). ``wiki_link`` visits name
the published Wiki whose "Generated by CodeNib" link the visitor followed.
"""

import re
import sys
from collections import Counter, defaultdict

PATTERN = re.compile(
    r"experience_event event=([a-z_]+) surface=(landing|wiki|cli) visit=([a-f0-9]{32})"
    r"(.*)$"
)
# The collector appends at most one arrival class and, for wiki_link, a name.
DETAIL = re.compile(
    r" arrival=(wiki_link|search|social|github|other)"
    r"(?: wiki=([A-Za-z0-9_.-]{1,100}(?:/[A-Za-z0-9_.-]{1,100})?))?"
)
ARRIVALS = ("search", "social", "github", "wiki_link", "other")


def summarize(lines):
    visits = defaultdict(lambda: defaultdict(dict))
    arrivals = defaultdict(dict)
    for position, line in enumerate(lines):
        match = PATTERN.search(line)
        if match:
            event, surface, visit, rest = match.groups()
            visits[surface][visit].setdefault(event, position)
            detail = DETAIL.fullmatch(rest.rstrip())
            arrival, wiki = detail.groups() if detail else (None, None)
            if arrival == "wiki_link" and not wiki:
                arrival = None
            if event == "page_view":
                # Keep the tab's first page view, as for every other event.
                arrivals[surface].setdefault(visit, (arrival, wiki))
    for surface, sessions in sorted(visits.items()):
        print(f"{surface}: {len(sessions)} observed tab visits")
        if arrivals[surface]:
            observed = list(arrivals[surface].values())
            counts = " ".join(
                f"{name}={sum(arrival == name for arrival, _ in observed)}"
                for name in ARRIVALS
            )
            unclassified = sum(arrival is None for arrival, _ in observed)
            print(f"  arrivals: {counts} direct_or_unknown={unclassified}")
            wikis = Counter()
            for arrival, wiki in observed:
                if arrival == "wiki_link" and wiki:
                    wikis[wiki] += 1
            for wiki, count in sorted(
                wikis.items(), key=lambda item: (-item[1], item[0])
            ):
                print(f"  wiki_link {wiki}: {count}")
        for event in (
            "page_view",
            "example_view",
            "example_source_open",
            "example_github_open",
            "example_wiki_open",
            "example_share",
            "repository_submit",
            "generation_form_view",
            "generation_start",
            "first_chapter_read",
            "agent_setup_open",
            "guard_case_view",
            "install_command_copy",
            "guard_first_run",
        ):
            print(f"  {event}: {sum(event in seen for seen in sessions.values())}")
        for start, finish in (
            ("example_view", "example_source_open"),
            ("repository_submit", "generation_start"),
            ("generation_start", "first_chapter_read"),
        ):
            cohort = [seen for seen in sessions.values() if start in seen]
            reached = sum(finish in seen for seen in cohort)
            print(f"  {start} -> {finish}: {reached}/{len(cohort)}")
        # A meaningful next step must be observed after evidence inspection,
        # using the first occurrence of either source event in this log stream.
        # This is a partial, same-origin tab observation, not attribution.
        source_events = ("example_source_open", "example_github_open")
        inspected = [
            (seen, min(seen[event] for event in source_events if event in seen))
            for seen in sessions.values()
            if any(event in seen for event in source_events)
        ]
        for finish in ("repository_submit", "agent_setup_open", "install_command_copy"):
            reached = sum(
                finish in seen and seen[finish] > source_position
                for seen, source_position in inspected
            )
            print(f"  source_inspection -> {finish}: {reached}/{len(inspected)}")


if __name__ == "__main__":
    summarize(sys.stdin)
